package ui

import (
	tea "charm.land/bubbletea/v2"
)

type model struct{}

func InitUI() *tea.Program {
	return tea.NewProgram(model{})
}

func (m model) Init() tea.Cmd {
	return nil
}

func (m model) Update(msg tea.Msg) (tea.Model, tea.Cmd) {
	switch msg := msg.(type) {
	case tea.KeyMsg:
		switch msg.String() {
		case "ctrl+c", "q":
			return m, tea.Quit
		}
	}

	return m, nil
}

func (m model) View() tea.View {
	return tea.String("Hello, World! Press 'q' or 'ctrl+c' to quit.")
}